#include "libft.h"

unsigned int	ft_lstsize(t_list *lst)
{
	unsigned int	size;

	size = 0;
	while (lst)
	{
		size++;
		lst = lst->next;
	}
	return (size);
}
#include <stdio.h>
int main()
{
	t_list *list;

	list = ft_lstnew("bir");
	ft_lstadd_back(&list, ft_lstnew("iki"));
	printf("%u\n", ft_lstsize(list));
	free(list);
	return(0);
}